export function trFood(name, lang = 'it') {
  const clean = String(name || '');
  if (lang === 'it') return clean;
  if (FOOD_DICT[clean]?.[lang]) return FOOD_DICT[clean][lang];
  let out = clean;
  if (lang === 'en') {
    out = out
      .replace('(Senza Glutine)', '(Gluten-Free)')
      .replace('(Senza Lattosio)', '(Lactose-Free)');
  } else if (lang === 'fr') {
    out = out
      .replace('(Senza Glutine)', '(Sans Gluten)')
      .replace('(Senza Lattosio)', '(Sans Lactose)');
  }
  return out;
}

export function trRecipeText(recipe, lang = 'it') {
  if (lang === 'it') return { title: recipe.n, steps: recipe.st };
  const dict = lang === 'en' ? STEP_WORDS_EN : STEP_WORDS_FR;
  let title = recipe.n;
  let steps = recipe.st;

  Object.entries(FOOD_DICT).forEach(([itKey, val]) => {
    const target = val[lang];
    if (target) {
      const rx = new RegExp(itKey.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'gi');
      title = title.replace(rx, target);
      steps = steps.replace(rx, target);
    }
  });

  dict.forEach(([itW, trW]) => {
    const rx = new RegExp(`\\b${itW}\\b`, 'gi');
    title = title.replace(rx, trW);
    steps = steps.replace(rx, trW);
  });

  return { title, steps };
}